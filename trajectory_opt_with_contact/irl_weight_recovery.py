"""
Inverse Optimal Control (IOC) / Inverse Reinforcement Learning (IRL)
for weight recovery in contact-implicit trajectory optimization.

Formulation:
    minimize_w  ||u*(w) - u_demo||^2
    subject to  sum(w_i) = 1
                w_i >= 0

Where:
    - u_demo: demonstrated control trajectory (from expert trajectory optimizer)
    - u*(w): optimal control for weight vector w
    - w: weight vector to recover [w_target, w_orient, w_v, w_ctrl, w_obs]
"""

import torch
import torch.nn.functional as F
import numpy as np
from typing import Dict, Optional, Tuple, List
from dataclasses import dataclass
import time

from .dynamics import rollout
from .optimizer import TrajectoryOptimizer


@dataclass
class IRLOptions:
    """Options for IRL weight recovery."""
    # Optimization settings
    max_outer_iters: int = 50          # Outer loop iterations for weight optimization
    max_inner_iters: int = 100         # Inner loop iterations for trajectory optimization
    lr_weights: float = 0.01           # Learning rate for weight optimization
    lr_trajectory: float = 0.01        # Learning rate for inner trajectory optimization
    
    # Method selection
    method: str = "feature_matching"   # "feature_matching" or "control_matching"
    
    # Convergence criteria
    weight_tol: float = 1e-4           # Tolerance for weight change
    control_tol: float = 1e-3          # Tolerance for control matching error
    
    # Regularization
    entropy_weight: float = 0.0        # Entropy regularization for weights (encourage diversity)
    l2_control_reg: float = 0.0        # L2 regularization on control difference
    
    # Feature scaling
    normalize_features: bool = False   # Normalize features to similar scale
    
    # Warm start
    warm_start_inner: bool = True      # Use previous solution for inner optimization
    
    # Logging
    verbose: bool = True


class IRLWeightRecovery:
    """
    Inverse Reinforcement Learning for weight recovery.
    
    Given a demonstration trajectory (u_demo) generated by an expert with unknown weights,
    recover the weight vector that best explains the demonstration.
    
    Example:
        >>> optimizer = TrajectoryOptimizer(...)
        >>> irl = IRLWeightRecovery(optimizer)
        >>> 
        >>> # Generate demonstration with known weights (expert)
        >>> demo = pack_demo(q0, v0, pusher0, goal, u_demo)
        >>> 
        >>> # Recover weights
        >>> w_recovered = irl.recover_weights(demo, method="feature_matching")
    """
    
    def __init__(self, optimizer: TrajectoryOptimizer):
        """
        Args:
            optimizer: TrajectoryOptimizer instance (contains dynamics, solver, etc.)
        """
        self.optimizer = optimizer
        self.device = optimizer.device
        
        # Feature names for logging
        self.feature_names = ['w_target', 'w_orient', 'w_v', 'w_ctrl', 'w_obs']
        self.n_features = len(self.feature_names)
    
    def recover_weights(
        self,
        demo: Dict,
        w_init: Optional[torch.Tensor] = None,
        opts: Optional[IRLOptions] = None
    ) -> Dict:
        """
        Recover weight vector from demonstration.
        
        Args:
            demo: Dictionary containing demonstration data:
                  - q0, v0, pusher0: Initial state
                  - goal: Goal configuration
                  - u_demo: Demonstrated control sequence (T, 2)
                  - obstacle_pos: Optional obstacle position
            w_init: Initial weight guess (optional, defaults to uniform)
            opts: IRLOptions instance (optional)
        
        Returns:
            result: Dictionary containing:
                - w_recovered: Recovered weight vector (normalized)
                - loss_history: Loss values over iterations
                - control_error_history: Control matching errors
                - converged: Whether optimization converged
                - num_iters: Number of iterations taken
                - u_final: Final control trajectory with recovered weights
        """
        if opts is None:
            opts = IRLOptions()
        
        # Extract demonstration data
        q0 = self._to_tensor(demo['q0'])
        v0 = self._to_tensor(demo['v0'])
        pusher0 = self._to_tensor(demo['pusher0'])
        goal = self._to_tensor(demo['goal'])
        u_demo = self._to_tensor(demo['u_demo'])
        obstacle_pos = None if demo.get('obstacle_pos') is None else self._to_tensor(demo['obstacle_pos'])
        
        if opts.verbose:
            print("\n" + "="*80)
            print("IRL Weight Recovery")
            print("="*80)
            print(f"Method: {opts.method}")
            print(f"Demonstration horizon: {u_demo.shape[0]}")
            print(f"Control dimension: {u_demo.shape[1]}")
        
        # Select recovery method
        if opts.method == "feature_matching":
            result = self._feature_matching_irl(
                q0, v0, pusher0, goal, u_demo, obstacle_pos, w_init, opts
            )
        elif opts.method == "control_matching":
            result = self._control_matching_irl(
                q0, v0, pusher0, goal, u_demo, obstacle_pos, w_init, opts
            )
        else:
            raise ValueError(f"Unknown method: {opts.method}")
        
        if opts.verbose:
            print("\n" + "="*80)
            print("Recovery Complete")
            print("="*80)
            self._print_weights(result['w_recovered'])
            print(f"Final control error: {result['control_error_history'][-1]:.6f}")
            print(f"Converged: {result['converged']}")
            print(f"Iterations: {result['num_iters']}")
        
        return result
    
    def _feature_matching_irl(
        self,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        u_demo: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor],
        w_init: Optional[torch.Tensor],
        opts: IRLOptions
    ) -> Dict:
        """
        Feature matching IRL (Abbeel & Ng, 2004 style).
        
        Idea: Match feature expectations between demonstration and learned policy.
        This is simpler than control matching as it doesn't require bi-level optimization.
        
        minimize_w  ||features(u*(w)) - features(u_demo)||^2
        subject to  sum(w) = 1, w >= 0
        """
        # Compute feature expectations from demonstration (no gradient needed)
        with torch.no_grad():
            features_demo = self._compute_features(q0, v0, pusher0, goal, u_demo, obstacle_pos)
        
        if opts.verbose:
            print("\nDemonstration features:")
            for i, (name, val) in enumerate(zip(self.feature_names, features_demo)):
                print(f"  {name}: {val:.6f}")
        
        # Initialize weights
        if w_init is None:
            w_raw = torch.zeros(self.n_features, dtype=torch.double, 
                               device=self.device, requires_grad=True)
        else:
            w_raw = torch.logit(w_init.clone()).requires_grad_(True)
        
        optimizer_w = torch.optim.Adam([w_raw], lr=opts.lr_weights)
        
        loss_history = []
        control_error_history = []
        u_current = None
        w_prev = None
        
        for iter in range(opts.max_outer_iters):
            optimizer_w.zero_grad()
            
            # Project to simplex using softmax
            w = F.softmax(w_raw, dim=0)
            
            # Solve trajectory optimization with current weights (no gradient through this)
            with torch.no_grad():
                u_current = self._solve_trajectory_with_weights(
                    w.detach(), q0, v0, pusher0, goal, obstacle_pos,
                    u_init=u_current if opts.warm_start_inner else None,
                    max_iters=opts.max_inner_iters,
                    lr=opts.lr_trajectory,
                    verbose=False
                )
            
            # Now compute features with gradient for current weights
            # We need gradient w.r.t. w, not u
            features_learned = self._compute_features_differentiable(
                q0, v0, pusher0, goal, u_current.detach(), obstacle_pos, w
            )
            
            # Feature matching loss
            feature_diff = features_learned - features_demo
            loss = torch.sum(feature_diff ** 2)
            
            # Optional: Entropy regularization (encourage diverse weights)
            if opts.entropy_weight > 0:
                entropy = -torch.sum(w * torch.log(w + 1e-10))
                loss = loss - opts.entropy_weight * entropy
            
            # Control matching error (for monitoring, not optimized)
            with torch.no_grad():
                control_error = torch.norm(u_current - u_demo).item()
            
            loss_history.append(loss.item())
            control_error_history.append(control_error)
            
            if opts.verbose and (iter % 10 == 0 or iter < 5):
                print(f"\nIter {iter:3d}:")
                print(f"  Feature loss: {loss.item():.6f}")
                print(f"  Control error: {control_error:.6f}")
                self._print_weights(w)
            
            # Check convergence
            if iter > 0 and w_prev is not None:
                weight_change = torch.norm(w - w_prev).item()
                if weight_change < opts.weight_tol and control_error < opts.control_tol:
                    if opts.verbose:
                        print(f"\nConverged at iteration {iter}")
                    break
            
            w_prev = w.detach().clone()
            
            # Backward pass
            loss.backward()
            optimizer_w.step()
        
        # Final features
        with torch.no_grad():
            features_final = self._compute_features(q0, v0, pusher0, goal, u_current, obstacle_pos)
        
        return {
            'w_recovered': F.softmax(w_raw, dim=0).detach(),
            'loss_history': loss_history,
            'control_error_history': control_error_history,
            'converged': control_error < opts.control_tol,
            'num_iters': iter + 1,
            'u_final': u_current.detach(),
            'features_demo': features_demo,
            'features_final': features_final
        }
    
    def _control_matching_irl(
        self,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        u_demo: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor],
        w_init: Optional[torch.Tensor],
        opts: IRLOptions
    ) -> Dict:
        """
        Direct control matching IRL.
        
        minimize_w  ||u*(w) - u_demo||^2
        subject to  sum(w) = 1, w >= 0
        
        This requires bi-level optimization and is more challenging but more accurate.
        """
        # Initialize weights
        if w_init is None:
            w_raw = torch.zeros(self.n_features, dtype=torch.double,
                               device=self.device, requires_grad=True)
        else:
            w_raw = torch.logit(w_init.clone()).requires_grad_(True)
        
        optimizer_w = torch.optim.Adam([w_raw], lr=opts.lr_weights)
        
        loss_history = []
        control_error_history = []
        u_current = None
        
        for iter in range(opts.max_outer_iters):
            optimizer_w.zero_grad()
            
            # Project to simplex
            w = F.softmax(w_raw, dim=0)
            
            # Solve inner trajectory optimization WITH unrolled differentiation
            u_current = self._solve_trajectory_with_weights(
                w, q0, v0, pusher0, goal, obstacle_pos,
                u_init=u_current if opts.warm_start_inner else None,
                max_iters=opts.max_inner_iters,
                lr=opts.lr_trajectory,
                verbose=False,
                keep_graph=True  # ← Enable unrolled differentiation!
            )
            
            # Direct control matching loss
            control_diff = u_current - u_demo
            loss = torch.sum(control_diff ** 2)
            
            # Optional L2 regularization
            if opts.l2_control_reg > 0:
                loss = loss + opts.l2_control_reg * torch.sum(u_current ** 2)
            
            control_error = torch.norm(control_diff).item()
            
            loss_history.append(loss.item())
            control_error_history.append(control_error)
            
            if opts.verbose and (iter % 10 == 0 or iter < 5):
                print(f"\nIter {iter:3d}:")
                print(f"  Control loss: {loss.item():.6f}")
                print(f"  Control error: {control_error:.6f}")
                self._print_weights(w)
            
            # Check convergence
            if iter > 0:
                weight_change = torch.norm(w - w_prev).item()
                if weight_change < opts.weight_tol and control_error < opts.control_tol:
                    if opts.verbose:
                        print(f"\nConverged at iteration {iter}")
                    break
            
            w_prev = w.detach().clone()
            
            # Backward pass (through entire optimization!)
            loss.backward()
            optimizer_w.step()
        
        return {
            'w_recovered': F.softmax(w_raw, dim=0).detach(),
            'loss_history': loss_history,
            'control_error_history': control_error_history,
            'converged': control_error < opts.control_tol,
            'num_iters': iter + 1,
            'u_final': u_current.detach()
        }
    
    def _solve_trajectory_with_weights(
        self,
        w: torch.Tensor,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor],
        u_init: Optional[torch.Tensor] = None,
        max_iters: int = 100,
        lr: float = 0.01,
        verbose: bool = False,
        keep_graph: bool = False  # NEW: control whether to keep gradient
    ) -> torch.Tensor:
        """
        Solve trajectory optimization with given weight vector.
        
        This is the inner optimization loop in bi-level IRL.
        
        Args:
            w: Weight vector [w_target, w_orient, w_v, w_ctrl, w_obs]
            keep_graph: If True, use unrolled differentiation (for control matching)
                       If False, use standard optimization (for feature matching)
        
        Returns:
            u_opt: Optimal control sequence (T, 2)
        """
        if keep_graph:
            # UNROLLED DIFFERENTIATION (for control matching)
            return self._solve_trajectory_unrolled(
                w, q0, v0, pusher0, goal, obstacle_pos, u_init, max_iters, lr, verbose
            )
        else:
            # STANDARD OPTIMIZATION (for feature matching)
            return self._solve_trajectory_standard(
                w, q0, v0, pusher0, goal, obstacle_pos, u_init, max_iters, lr, verbose
            )
    
    def _solve_trajectory_standard(
        self,
        w: torch.Tensor,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor],
        u_init: Optional[torch.Tensor],
        max_iters: int,
        lr: float,
        verbose: bool
    ) -> torch.Tensor:
        """
        Standard trajectory optimization (no gradient tracking).
        Used for feature matching.
        """
        # Initialize controls
        if u_init is None:
            u_seq = torch.zeros(self.optimizer.horizon, 2, 
                               dtype=torch.double, device=self.device, 
                               requires_grad=True)
        else:
            u_seq = u_init.clone().detach().requires_grad_(True)
        
        opt = torch.optim.Adam([u_seq], lr=lr)
        
        for iter in range(max_iters):
            opt.zero_grad()
            
            # Compute weighted cost
            loss = self._weighted_rollout(
                u_seq, q0, v0, pusher0, goal, w.detach(), obstacle_pos
            )
            
            loss.backward()
            opt.step()
            
            if verbose and iter % 20 == 0:
                print(f"    Inner iter {iter}: loss = {loss.item():.6f}")
        
        return u_seq.detach()
    
    def _solve_trajectory_unrolled(
        self,
        w: torch.Tensor,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor],
        u_init: Optional[torch.Tensor],
        max_iters: int,
        lr: float,
        verbose: bool
    ) -> torch.Tensor:
        """
        Unrolled differentiation using functional gradient descent.
        
        Key: grad_u = ∇_u L(u; w) must maintain gradient w.r.t. w!
        This is achieved with create_graph=True.
        """
        # Initialize
        if u_init is None:
            u = torch.zeros(self.optimizer.horizon, 2, 
                           dtype=torch.double, device=self.device)
        else:
            u = u_init.clone().detach()
        
        # Functional gradient descent
        for iter in range(max_iters):
            # Make u require gradient for THIS iteration
            u = u.detach().requires_grad_(True)
            
            # Compute loss (depends on both u and w)
            loss = self._weighted_rollout(
                u, q0, v0, pusher0, goal, w, obstacle_pos
            )
            
            # CRITICAL: create_graph=True to maintain w gradient!
            # grad_u = ∂L/∂u, but this also depends on w
            grad_u = torch.autograd.grad(
                outputs=loss,
                inputs=u,
                create_graph=True  # ← This is the key!
            )[0]
            
            # Functional update: u_new = u - lr * grad_u
            # Since grad_u depends on w, u_new also depends on w!
            u = u - lr * grad_u
            
            if verbose and iter % 20 == 0:
                with torch.no_grad():
                    print(f"    Inner iter {iter}: loss = {loss.item():.6f}")
        
        # u now has gradient w.r.t. w through entire optimization chain
        return u
    
    def _weighted_rollout(
        self,
        u_seq: torch.Tensor,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        w: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor]
    ) -> torch.Tensor:
        """
        Rollout with weighted cost function.
        
        Args:
            w: Weight vector [w_target, w_orient, w_v, w_ctrl, w_obs]
        
        Returns:
            loss: Weighted total cost
        """
        loss, q_final, lambdas, phis, qs, pusher_traj, \
            goal_term, orient_term, ctrl_term, v_term, obs_term, pen_term = rollout(
                u_seq, q0, v0, pusher0,
                self.optimizer.horizon, self.optimizer.dt,
                self.optimizer.m, self.optimizer.Izz, 
                self.optimizer.half, self.optimizer.mu, goal,
                w_target=w[0], w_orient=w[1], w_v=w[2], 
                w_ctrl=w[3], w_obs=w[4],
                qp_solver=self.optimizer.qp_solver,
                dynamics_solver=self.optimizer.dynamics_solver,
                obstacle_pos=obstacle_pos,
                device=self.device
            )
        
        return loss
    
    def _compute_features(
        self,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        u_seq: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor]
    ) -> torch.Tensor:
        """
        Compute feature values for a given trajectory.
        
        Features correspond to the individual cost terms:
        - goal_term: position error
        - orient_term: orientation error
        - v_term: terminal velocity
        - ctrl_term: control effort
        - obs_term: obstacle avoidance
        
        Returns:
            features: Tensor of shape (n_features,) containing feature values
        """
        with torch.no_grad():
            _, q_final, lambdas, phis, qs, pusher_traj, \
                goal_term, orient_term, ctrl_term, v_term, obs_term, pen_term = rollout(
                    u_seq, q0, v0, pusher0,
                    self.optimizer.horizon, self.optimizer.dt,
                    self.optimizer.m, self.optimizer.Izz,
                    self.optimizer.half, self.optimizer.mu, goal,
                    w_target=1.0, w_orient=1.0, w_v=1.0, 
                    w_ctrl=1.0, w_obs=1.0,
                    qp_solver=self.optimizer.qp_solver,
                    dynamics_solver=self.optimizer.dynamics_solver,
                    obstacle_pos=obstacle_pos,
                    device=self.device
                )
        
        # Return unweighted feature values
        return torch.tensor([
            goal_term.item(),
            orient_term.item(),
            v_term.item(),
            ctrl_term.item(),
            obs_term.item()
        ], dtype=torch.double, device=self.device)
    
    def _compute_features_differentiable(
        self,
        q0: torch.Tensor,
        v0: torch.Tensor,
        pusher0: torch.Tensor,
        goal: torch.Tensor,
        u_seq: torch.Tensor,
        obstacle_pos: Optional[torch.Tensor],
        w: torch.Tensor
    ) -> torch.Tensor:
        """
        Compute weighted features with gradient w.r.t. weights.
        
        This is used in feature matching where we need gradient through weights
        but NOT through the trajectory (u_seq should be detached).
        
        Args:
            w: Weight vector (requires_grad=True)
            u_seq: Control sequence (detached, no gradient)
        
        Returns:
            weighted_features: Weighted sum of features (differentiable w.r.t. w)
        """
        # Compute unweighted features (no gradient)
        features = self._compute_features(q0, v0, pusher0, goal, u_seq, obstacle_pos)
        
        # Weight them (gradient flows through w)
        # We return the features themselves, not weighted sum
        # The weighting happens implicitly through the loss computation
        return features
    
    def _to_tensor(self, x, requires_grad=False):
        """Convert input to tensor."""
        if not isinstance(x, torch.Tensor):
            x = torch.tensor(x, dtype=torch.double, device=self.device)
        else:
            x = x.to(dtype=torch.double, device=self.device)
        x.requires_grad = requires_grad
        return x
    
    def _print_weights(self, w: torch.Tensor):
        """Pretty print weight vector."""
        print("  Weights:")
        for name, val in zip(self.feature_names, w):
            print(f"    {name:12s}: {val.item():.6f}")


def pack_demo(q0, v0, pusher0, goal, u_demo, obstacle_pos=None) -> Dict:
    """
    Create a canonical demo dict for IRL.
    
    Args:
        q0, v0, goal: State and goal (arrays)
        pusher0: Pusher position (array)
        u_demo: Control trajectory (T, 2)
        obstacle_pos: Optional obstacle position
    
    Returns:
        demo: Dictionary containing all demonstration data
    """
    def to_numpy(x):
        if isinstance(x, torch.Tensor):
            return x.detach().cpu().numpy()
        return np.asarray(x)
    
    return dict(
        q0=to_numpy(q0),
        v0=to_numpy(v0),
        pusher0=to_numpy(pusher0),
        goal=to_numpy(goal),
        u_demo=to_numpy(u_demo),
        obstacle_pos=None if obstacle_pos is None else to_numpy(obstacle_pos),
    )