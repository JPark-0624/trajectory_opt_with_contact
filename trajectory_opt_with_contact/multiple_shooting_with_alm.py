    def check_stationarity(self, outer, uSeq, qKnots, prKnots, 
                        defectNorm, terminalNorm, cfg):
        """
        Check KKT-like stationarity conditions for ALM.
        """
        with torch.no_grad():
            # 1. Gradient norms (should be small after inner convergence)
            grad_u = uSeq.grad.norm().item() if uSeq.grad is not None else 0.0
            grad_q = sum(qKnots[j].grad.norm().item() 
                        for j in range(1, len(qKnots)) 
                        if qKnots[j].grad is not None)
            grad_pr = sum(prKnots[j].grad.norm().item() 
                        for j in range(1, len(prKnots)) 
                        if prKnots[j].grad is not None)
            
            total_grad = grad_u + grad_q + grad_pr
            
            # 2. Constraint violations
            defect_viol = defectNorm.item()
            terminal_viol = terminalNorm.item()
            total_viol = defect_viol + terminal_viol
            
            # 3. Stationarity criteria
            grad_threshold = 1e-2  # Gradient should be small
            feas_threshold = cfg.tolDefect
            
            grad_ok = total_grad < grad_threshold
            feas_ok = total_viol < feas_threshold
            
            print(f"\n[Stationarity Check - Outer {outer+1}]")
            print(f"  Gradients: ||∇u||={grad_u:.3e}, ||∇q||={grad_q:.3e}, ||∇pr||={grad_pr:.3e}")
            print(f"    Total: {total_grad:.3e} {'✅' if grad_ok else '❌'} (threshold: {grad_threshold:.3e})")
            print(f"  Constraints: Defect={defect_viol:.3e}, Terminal={terminal_viol:.3e}")
            print(f"    Total: {total_viol:.3e} {'✅' if feas_ok else '❌'} (threshold: {feas_threshold:.3e})")
            
            is_stationary = grad_ok and feas_ok
            print(f"  Stationarity: {'✅ CONVERGED' if is_stationary else '❌ Not converged'}")
            
            return is_stationary, {
                'grad_u': grad_u,
                'grad_q': grad_q,
                'grad_pr': grad_pr,
                'total_grad': total_grad,
                'defect': defect_viol,
                'terminal': terminal_viol,
                'total_violation': total_viol,
                'converged': is_stationary
            }


    def optimize(
        self,
        q0: torch.Tensor,         # [3] object initial pose
        v0: torch.Tensor,         # [3] object initial velocity
        pr0: torch.Tensor,        # [2] pusher initial pose
        goalXY: torch.Tensor,     # [2]
        goalTheta: Optional[float] = None,
        cfg: Optional[ALMConfig] = None,
        w: Optional[CostWeights] = None,
        # initial guesses
        uInit: Optional[torch.Tensor] = None,            # [T,2]
        qKnotInit: Optional[torch.Tensor] = None,        # [K,3]
        prKnotInit: Optional[torch.Tensor] = None,       # [K,2]
    ) -> Dict[str, torch.Tensor]:
        """Run block multiple-shooting with ALM."""
        if cfg is None:
            cfg = ALMConfig()
        if w is None:
            w = CostWeights()
        # Move inputs to device
        q0 = q0.to(self.device)
        v0 = v0.to(self.device)
        pr0 = pr0.to(self.device)
        goalXY = goalXY.to(self.device)

        # Initialize primal variables
        T = self.horizon
        K = self.numKnots
        B = self.blockSize

        if uInit is None:
            uInit = torch.zeros(T, 2, device=self.device)
        else:
            uInit = uInit.to(self.device)

        if qKnotInit is None:
            qKnotInit = torch.zeros(K, 3, device=self.device)
            qKnotInit[0] = q0
        else:
            qKnotInit = qKnotInit.to(self.device)
            qKnotInit[0] = q0

        if prKnotInit is None:
            prKnotInit = torch.zeros(K, 2, device=self.device)
            prKnotInit[0] = pr0
        else:
            prKnotInit = prKnotInit.to(self.device)
            prKnotInit[0] = pr0

        # Primal params
        uSeq = torch.nn.Parameter(uInit.clone())
        qKnots = torch.nn.Parameter(qKnotInit.clone())
        prKnots = torch.nn.Parameter(prKnotInit.clone())

        # Fix knot 0 to initial state by overwriting each iteration (simplest)
        def _enforceInitialKnot():
            with torch.no_grad():
                qKnots.data[0].copy_(q0)
                prKnots.data[0].copy_(pr0)

        # ALM state init
        self.resetAlmState(cfg)

        

        # sched = torch.optim.lr_scheduler.StepLR(optimizer, step_size=cfg.lrDecayStep, gamma=cfg.lrDecayGamma)

        # Logs
        history = {
            "outerLoss": [],
            "terminalXYNorm": [],
            "terminalThetaAbs": [],
            "defectNorm": [],
            "rhoTerminalXY": [],
            "rhoTerminalTheta": [],
            "rhoDefect": [],
        }

        for outer in range(cfg.outerIters):
            _enforceInitialKnot()
            # reset scheduler each outer iter
            # Optimizer setup
            if cfg.useLbfgs:
                optimizer = torch.optim.LBFGS(
                    [uSeq, qKnots, prKnots],
                    max_iter=cfg.lbfgsMaxIter,
                    history_size=cfg.lbfgsHistorySize,
                    line_search_fn="strong_wolfe",
                )
            else:
                # optimizer = torch.optim.Adam([uSeq, qKnots, prKnots], lr=cfg.lr)
                optimizer = torch.optim.Adam([uSeq, qKnots, prKnots], lr=cfg.lr)
        
            sched = torch.optim.lr_scheduler.StepLR(optimizer, step_size=cfg.lrDecayStep, gamma=cfg.lrDecayGamma)

            def closure():
                optimizer.zero_grad(set_to_none=True)
                _enforceInitialKnot()

                # Soft costs
                controlEnergy = (uSeq ** 2).sum()
                controlSmooth = ((uSeq[1:] - uSeq[:-1]) ** 2).sum() if T > 1 else torch.zeros((), device=self.device)

                objVelEnergy = torch.zeros((), device=self.device)

                # Defects and ALM terms
                defectNormSq = torch.zeros((), device=self.device)
                almDefect = torch.zeros((), device=self.device)
                lamdas = []
                phis = []
                qs = []
                qrobot_hist = []

                # Simulate each block from knot j to get predicted end, build defect at knot j+1
                for j in range(self.numBlocks):
                    t0 = j * B
                    t1 = min((j + 1) * B, T)
                    steps = t1 - t0

                    qStart = qKnots[j]
                    prStart = prKnots[j]
                    # We do not lift object velocity knot; start v is only available for block0.
                    # For later blocks, we set vStart=0 as a pragmatic approximation; for higher fidelity,
                    # lift v at knots too (optional).
                    if j == 0:
                        vStart = v0.detach().requires_grad_(True)
                    else:
                        vStart = torch.zeros(3, device=self.device, dtype=v0.dtype, requires_grad=True)

                    qEndPred, vEndPred, prEndPred, objVelEnergyBlock, lamdaBlock, phisBlock, qsBlock, qrobot_histBlock = self._simulateBlock(
                        qStart, vStart, prStart, uSeq[t0:t1], steps
                    )
                    objVelEnergy = objVelEnergy + objVelEnergyBlock

                    if j ==0:
                        qs.extend(qsBlock)
                        qrobot_hist.extend(qrobot_histBlock)
                        lamdas.extend(lamdaBlock)
                        phis.extend(phisBlock)
                    
                    else:
                        qs.extend(qsBlock[1:])
                        qrobot_hist.extend(qrobot_histBlock[1:])
                        lamdas.extend(lamdaBlock[1:])
                        phis.extend(phisBlock[1:])

                    if self.enableDefectALM:
                        # defect residual: [dx,dy,dth,dpx,dpy]
                        dq = qKnots[j + 1] - qEndPred
                        dpr = prKnots[j + 1] - prEndPred
                        d = torch.cat([dq, dpr], dim=0)  # [5]

                        defectNormSq = defectNormSq + (d ** 2).sum()

                        lam = self.lamDefect[j]
                        almDefect = almDefect + (lam * d).sum() + 0.5 * self.rhoDefect * (d ** 2).sum()

                # Terminal ALM
                rXY = qKnots[-1][:2] - goalXY
                terminalXYNormSq = (rXY ** 2).sum()
                targetCost = w.wTargetXY * terminalXYNormSq

                targetOrientCost = torch.zeros((), device=self.device)
                if goalTheta is not None:
                    rTh = wrap_to_pi(qKnots[-1][2] - torch.as_tensor(goalTheta, device=self.device))
                    targetOrientCost = w.wTargetOrient * (rTh ** 2)

                # Total objective
                soft = (
                    w.wControl * controlEnergy
                    + w.wControlSmooth * controlSmooth
                    + w.wObjVel * objVelEnergy
                    + targetCost
                    + targetOrientCost
                )

                total = soft + almDefect

                total.backward()
                grad_norm = uSeq.grad.norm().item()
                print(f"Inner iter closure: total loss: {total.item():.4f} | "
                      f"grad norm: {grad_norm:.4f} | "
                      f"object pose {qs[-1].detach().cpu().numpy()} | ")

                return {
                    "total": total,
                    "soft": soft,
                    "almDefect": almDefect,
                    "controlEnergy": controlEnergy,
                    "controlSmooth": controlSmooth,
                    "objVelEnergy": objVelEnergy,
                    "lamdas": torch.stack(lamdas) if lamdas else torch.empty(0, 2, device=self.device),
                    "phis": torch.stack(phis) if phis else torch.empty(0, device=self.device),
                    "qs": torch.stack(qs) if qs else torch.empty(0, 3, device=self.device),
                    "qrobot_hist": torch.stack(qrobot_hist) if qrobot_hist else torch.empty(0, 2, device=self.device)
                }
            

            # Inner optimization
            if cfg.useLbfgs:
                result = optimizer.step(closure)
                
            else:
                lossVal = None
                for _ in range(cfg.innerIters):
                    result = closure()
                    optimizer.step()
                    sched.step()

            lossVal = result["total"] if isinstance(result, dict) else None
            qs = result["qs"] if isinstance(result, dict) else None
            pusherTraj = result["qrobot_hist"] if isinstance(result, dict) else None
            contactImpulses = result["lamdas"] if isinstance(result, dict) else None
            signedDistances = result["phis"] if isinstance(result, dict) else None

            print(
                    f"Loss={lossVal.item() if lossVal is not None else 'N/A':.4f}, "
                    f"Final obj pose : {qs[-1].detach().cpu().numpy()}, Goal pose: {goalXY.detach().cpu().numpy()},{goalTheta})"
                )


            # Evaluate residuals with current params (no grad)
            with torch.no_grad():
                _enforceInitialKnot()

                # Terminal residual
                rXY = (qKnots[-1][:2] - goalXY)
                terminalXYNorm = rXY.norm()

                # Defect residual aggregate
                defectNorm = torch.zeros((), device=self.device)
                if self.enableDefectALM:
                    # recompute defects quickly (one pass)
                    for j in range(self.numBlocks):
                        t0 = j * B
                        t1 = min((j + 1) * B, T)
                        steps = t1 - t0

                        qStart = qKnots[j]
                        prStart = prKnots[j]
                        vStart = v0 if j == 0 else torch.zeros_like(v0)
                        qEndPred, vEndPred, prEndPred, _,_,_,_,_ = self._simulateBlock(
                            qStart, vStart, prStart, uSeq[t0:t1].detach(), steps
                        )

                        d = torch.cat([qKnots[j + 1] - qEndPred, prKnots[j + 1] - prEndPred], dim=0)
                        
                        defectNorm = defectNorm + d.norm()
                    
                        self.lamDefect[j] = self.lamDefect[j] + self.rhoDefect * d

                    # Rho schedule for defects
                    if defectNorm.item() > cfg.tolDefect:
                        self.rhoDefect = min(self.rhoDefect * cfg.rhoDefectEta, cfg.rhoDefectMax)


                terminalThetaAbs = torch.zeros((), device=self.device)
                rTh = wrap_to_pi(qKnots[-1][2] - torch.as_tensor(goalTheta, device=self.device))
                terminalThetaAbs = rTh.abs()

                is_stationary, stat_info = self.check_stationarity(
                                            outer, uSeq, qKnots, prKnots, 
                                            defectNorm, terminalXYNorm, cfg
                                        )
                
                

                # Log
                history["outerLoss"].append(lossVal.detach().cpu() if lossVal is not None else torch.tensor(float("nan")))
                history["terminalXYNorm"].append(terminalXYNorm.detach().cpu())
                history["terminalThetaAbs"].append(terminalThetaAbs.detach().cpu())
                history["defectNorm"].append(defectNorm.detach().cpu())
                history["rhoTerminalXY"].append(torch.tensor(self.rhoTerminalXY))
                history["rhoTerminalTheta"].append(torch.tensor(self.rhoTerminalTheta))
                history["rhoDefect"].append(torch.tensor(self.rhoDefect))
                
                if is_stationary and outer >= 2:  # At least 3 outer iterations
                    print("Early stopping: stationarity achieved!")
                    break
    

                print(
                    f"Outer iter {outer+1}/{cfg.outerIters}: "
                    f"Loss={lossVal.item() if lossVal is not None else 'N/A':.4f}, "
                    f"||rXY||={terminalXYNorm.item():.6f}, "
                    f"|rTh|={terminalThetaAbs.item():.6f}, "
                    f"DefectNorm={defectNorm.item():.6f}, "
                    f"rhoTerminalXY={self.rhoTerminalXY:.1f}, "
                    f"rhoTerminalTheta={self.rhoTerminalTheta:.1f}, "
                    f"rhoDefect={self.rhoDefect:.1f}"
                )


